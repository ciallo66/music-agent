# 乐理与制作：补充常见追问点
THEORY_ENTRIES: tuple[str, ...] = (
    "主导动机（Leitmotif）指用一段固定旋律或和声代表特定角色、地点或情绪，"
    "在配乐中反复出现并随情节变奏，是影视与游戏配乐常见的叙事手法。",
    "降弦（Drop Tuning）指把最低弦调低若干音，使强力和弦可用一根手指按出，"
    "音色更低更厚重，常见于金属与重型摇滚。",
    "吼腔与清嗓（Harsh / Clean Vocals）是金属与摇滚人声的两大类："
    "吼腔包含嘶吼、低吼与尖叫等嗓音技术，清嗓为常规歌唱音色，"
    "许多作品在同一首歌里交替使用两者形成对比。",
    "古典音乐的时期划分通常分为巴洛克（约 1600–1750）、古典主义（约 1750–1820）、"
    "浪漫主义（约 1820–1900）与现代/当代，各时期在编制、和声与曲式上有明显差异。",
    "编曲（Arrangement）指为已有旋律安排乐器、和声、节奏与段落的过程，"
    "决定作品的音色层次与动态走向，与作曲、混音是不同环节。",
    "采样（Sampling）指截取已有录音片段并用于新作品，"
    "是嘻哈与电子音乐的核心手法，使用时需注意版权授权。",
    "混响与延迟（Reverb / Delay）是两种常用空间效果：混响模拟空间反射塑造距离感，"
    "延迟产生重复回声，常用于氛围与后摇铺陈。",
    "失真与过载（Distortion / Overdrive）是通过削波改变吉他音色的效果，"
    "过载较温和保留动态，失真更强烈且压缩感明显，是摇滚与金属的标志音色。",
)

# 音频特征：补充容易被追问的指标
FEATURE_ENTRIES: tuple[str, ...] = (
    "起音密度（Onset Rate）表示每秒检测到的音符起始次数，数值越高说明音符越密集，"
    "是衡量节奏活跃度的指标之一，单位通常为次/秒。",
    "频谱质心（Spectral Centroid）是声音频谱的「重心」频率，数值越高听感越明亮、"
    "越偏「金属感」，数值越低越暗沉厚重，单位通常为赫兹。",
    "BPM 与听感速度的差异：同一首歌的 BPM 固定，但半速感（half-time）编配会让听众"
    "感觉慢一半，因为鼓组把重音放在每两拍一次。",
    "人声概率（Voice Probability）是分类器给出的判定置信度，"
    "数值接近 1 表示该曲偏人声，接近 0 表示偏器乐；它是概率而非绝对结论，"
    "边界样本需要结合听感判断。",
)

