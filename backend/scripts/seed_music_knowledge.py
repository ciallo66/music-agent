def parse_args() -> argparse.Namespace:
    """解析导入命令参数。"""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true", help="只统计不写入")
    return parser.parse_args()


def seed_knowledge(dry_run: bool = False) -> tuple[int, int]:
    """按 content 幂等写入知识切片，返回（新增数, 已存在跳过数）。"""
    created = 0
    skipped = 0
    with SessionLocal() as db:
        existing = set(db.scalars(select(MusicKnowledge.content)).all())
        for content, source in KNOWLEDGE_ENTRIES:
            if content in existing:
                skipped += 1
                continue
            if not dry_run:
                db.add(MusicKnowledge(content=content, source=source))
            created += 1
        if dry_run:
            db.rollback()
        else:
            db.commit()
    return created, skipped


def main() -> None:
    """执行知识库导入并输出统计。"""
    args = parse_args()
    created, skipped = seed_knowledge(dry_run=args.dry_run)
    action = "待写入" if args.dry_run else "已写入"
    print(f"知识切片：{action} {created} 条，已存在跳过 {skipped} 条")
    if args.dry_run:
        print("（预览模式，未写入数据库）")


if __name__ == "__main__":
    main()
